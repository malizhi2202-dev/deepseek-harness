/**
 * `sidebarAutomation` namespace dictionaries, and the namespace's declaration.
 *
 * The panel's copy is split by the question it answers: the type's name and
 * guide box, the workspace's own state, the ledger's run list, and then the four
 * questions the design requires of every run — what it compared, what it did or
 * why it did not, the paths it named, and what happens next.
 *
 * Every outcome the ledger can record has its own line, because a run that
 * refused, was superseded, or correctly did nothing is the case a reader has to
 * be able to explain; no variant falls back to a generic sentence.
 *
 * A commit id, a path, a failure message, and a summary source are data rather
 * than copy, so they travel through these lines as parameters instead of
 * becoming keys.
 *
 * The namespace merge lives with its key set so that any module naming
 * `TranslateNS<'sidebarAutomation'>` or `PropsLocale<'sidebarAutomation'>` needs
 * only this file, whichever entry a program loads first.
 */
